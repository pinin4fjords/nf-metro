"""Score a render-diff fixture pair with the fitted layout objective.

``fit_objective.py`` owns the fitted weights: ``iter2_weights.json`` (a sibling
of this file) is regenerated by

    python fit_objective.py --dump-weights iter2 --weights-out ../iter2_weights.json

This module is the only consumer that turns those weights plus a feature
vector into the single number the render-diff reports: the aggregate weighted
delta between a fixture's base and PR renders. It holds no weight of its own.

**Shadow mode only.** Nothing here gates CI -- see the hard boundary in
``datasets/layout_preferences/README.md``. The weights carry negative terms
that would be harmful under minimisation; this module never optimises
anything, only reports a delta for a human to read.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from nf_metro.layout.routing.common import RoutedPath
    from nf_metro.parser.model import MetroGraph

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import extract_features  # noqa: E402
import fit_objective  # noqa: E402

WEIGHTS_PATH = HERE.parent / "iter2_weights.json"


def load_weights(path: Path = WEIGHTS_PATH) -> dict:
    """The committed weights artifact fit_objective.py's ``--dump-weights`` wrote."""
    return json.loads(path.read_text())


def feature_keys(weights: dict | None = None) -> list[str]:
    """The feature names this objective needs, read off the weights artifact.

    Never hardcoded here: the moment fit_objective.py's ``iter2`` feature set
    changes and the artifact is regenerated, this list changes with it --
    there is no second place that would fall out of sync.
    """
    weights = weights if weights is not None else load_weights()
    return sorted(weights["weights"])


class _DrawnRoute:
    """Adapts an already-drawn polyline to what ``extract_features.path_points`` reads.

    ``extract_features.features`` is written against a graph's routed paths
    (``route.points`` / ``route.line_id``), for replaying historical
    revisions where nothing has been rendered yet. A render-diff fixture
    *has* been rendered, so this stands in for a route object carrying the
    coordinates the renderer actually drew (offset-applied, post label
    growth) rather than re-deriving them with a second routing pass.
    """

    __slots__ = ("points", "line_id")

    def __init__(self, points: list[tuple[float, float]], line_id: object) -> None:
        self.points = points
        self.line_id = line_id


def learned_features(
    graph: MetroGraph,
    drawn_polylines: list[tuple[RoutedPath, list[tuple[float, float]]]],
) -> dict[str, float]:
    """The raw feature values this objective reads, off already-drawn geometry.

    ``drawn_polylines`` is the render-diff's own ``layout_metrics.drawn_polylines()``
    output: one ``(route, points)`` pair per routed path, points already
    offset-applied. Delegates the actual computation to
    ``extract_features.features``, so a feature's definition cannot drift
    between what the objective was fitted against and what the scorecard
    reports -- only the geometry *source* differs (drawn/rendered here, a
    fresh routing pass in the historical replay that produced the corpus).
    """
    routes = [_DrawnRoute(pts, route.line_id) for route, pts in drawn_polylines]
    full = extract_features.features(graph, routes)
    keys = feature_keys()
    return {k: full[k] for k in keys if k in full}


def score_delta(
    before: dict[str, float] | None,
    after: dict[str, float] | None,
    weights: dict | None = None,
) -> float | None:
    """Aggregate weighted delta base->PR: negative better, positive worse.

    Mirrors ``fit_objective.Pair.delta``'s sentinel masking: a feature
    undefined on either side (e.g. ``min_marker_gap`` when no non-consumer
    line comes near any marker) contributes nothing, rather than being read
    as the extreme sentinel value -1.0.

    ``None`` when either side has no feature vector at all (a render that
    predates this scorecard, or whose metrics computation failed).
    """
    if not before or not after:
        return None
    w = weights if weights is not None else load_weights()
    scaled = w["weights"]
    b, a = fit_objective.derive(before), fit_objective.derive(after)
    total = 0.0
    for key, weight in scaled.items():
        bv, av = b.get(key), a.get(key)
        if bv is None or av is None:
            continue
        total += weight * (av - bv)
    return total
